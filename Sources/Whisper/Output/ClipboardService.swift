import AppKit

/// Writes text to the general pasteboard, and saves and restores whatever the
/// user had on it around a paste.
enum ClipboardService {
    /// Everything on the pasteboard: each item with each of its types. Text
    /// alone would lose a copied image or file, and turn rich text plain.
    struct Snapshot {
        fileprivate let items: [[NSPasteboard.PasteboardType: Data]]
    }

    /// Markers clipboard managers look for (nspasteboard.org): this entry is
    /// short-lived and machine-written, so leave it out of the history.
    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static func snapshot() -> Snapshot {
        let items = (NSPasteboard.general.pasteboardItems ?? []).map { item in
            var contents: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { contents[type] = data }
            }
            return contents
        }
        return Snapshot(items: items)
    }

    /// Puts `text` on the pasteboard and returns the pasteboard's change count
    /// afterwards. `transient` marks it as passing through, for a transcript
    /// that is pasted and then replaced by what was there before.
    @discardableResult
    static func set(_ text: String, transient: Bool = false) -> Int {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            for type in transientTypes { item.setData(Data(), forType: type) }
        }
        pb.writeObjects([item])
        return pb.changeCount
    }

    /// Puts a snapshot back, but only if the pasteboard still holds what we
    /// wrote (`expecting` is the count `set` returned). If the user or another
    /// app has copied something since, theirs is newer and stays.
    static func restore(_ snapshot: Snapshot, expecting changeCount: Int) {
        let pb = NSPasteboard.general
        guard pb.changeCount == changeCount else { return }
        pb.clearContents()
        let items = snapshot.items.filter { !$0.isEmpty }.map { contents -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in contents { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }
}
